// 検索質問プール。上位5問で全体の約50%を占めるよう重み付け(docs/06 §3 S1)。
// 実際のFAQは同種質問が繰り返される性質を反映し、キャッシュヒット率を現実的にする。

export const POPULAR = '医療脱毛の当日キャンセル料はいくらですか';

// [質問, 重み]
const POOL = [
  [POPULAR, 20],
  ['ボトックス施術後に飲酒はいつから可能ですか', 12],
  ['ダーマペンのダウンタイムはどのくらいですか', 10],
  ['ヒアルロン酸注入の禁忌を教えてください', 8],
  ['初診の患者様への案内フローを教えて', 6],
  ['ケミカルピーリング後のスキンケアの注意点は', 4],
  ['ポテンツァとダーマペンの違いは', 4],
  ['予約の変更・キャンセルの締め切りはいつですか', 4],
  ['水光注射の料金はいくらですか', 3],
  ['しみ取りレーザー後のダウンタイムは', 3],
  ['脂肪溶解注射の禁忌はありますか', 3],
  ['クレジットカードは使えますか', 3],
  ['遅刻した場合はどうなりますか', 3],
  ['術後の腫れが続く場合の対応は', 3],
  ['接客時の言葉遣いのルールは', 2],
  ['院内での身だしなみ規定は', 2],
  ['カウンセリングの流れを教えて', 2],
  ['未成年の施術に親の同意は必要ですか', 2],
  ['施術前の注意事項は', 1],
  ['アフターケアの問い合わせ対応は', 1],
];

// 重み付き累積配列
const CUM = [];
let total = 0;
for (const [q, w] of POOL) {
  total += w;
  CUM.push([total, q]);
}

export function randomQuestion() {
  const r = Math.random() * total;
  for (const [c, q] of CUM) {
    if (r <= c) return q;
  }
  return POOL[0][0];
}
